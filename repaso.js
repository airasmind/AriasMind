(function(){
  var box = document.getElementById('repaso');
  var num = parseInt(document.body.getAttribute('data-article') || box && box.getAttribute('data-article') || '0', 10);
  if(!box || !window.REPASO || !REPASO[num]) return;
  var data = REPASO[num], N = data.preguntas.length, notas = {};
  var KEY = 'ariasmind_repaso';
  function leer(){ try{ return JSON.parse(localStorage.getItem(KEY) || '{}'); }catch(e){ return {}; } }
  function guardar(v){ try{ var d = leer(); d[num] = v; localStorage.setItem(KEY, JSON.stringify(d)); }catch(e){} }
  function track(n){ try{ if(window.gtag) gtag('event', n, {articulo: num}); }catch(e){} }
  var art = (window.ARTICULOS_TODOS || []).filter(function(a){ return a.n === num; })[0] || {};

  var previo = leer()[num], aviso = '';
  if(previo && previo.fecha){
    var dias = Math.floor((Date.now() - previo.fecha) / 864e5);
    var cuando = dias <= 0 ? 'hoy' : dias === 1 ? 'ayer' : 'hace ' + dias + ' días';
    aviso = '<p class="rp-prev">La última vez (' + cuando + ') recordaste ' + previo.bien + ' de ' + N + '. A ver ahora.</p>';
  }

  var html = '<h2 class="rp-hdr" id="rp-t">¿Qué recuerdas?</h2>' +
    '<p class="rp-lead">Sin volver a leer, intenta responder cada pregunta en tu cabeza o en voz alta. Después mira la respuesta y sé honesto contigo. Recordar con esfuerzo es lo que hace que algo se quede.</p>' + aviso + '<ol class="rp-list">';
  data.preguntas.forEach(function(q, i){
    html += '<li class="rp-q" data-i="' + i + '"><p class="rp-p">' + q[0] + '</p>' +
      '<button class="btn btn-secondary rp-ver" type="button" aria-expanded="false" aria-controls="rp-a' + i + '">Ver respuesta</button>' +
      '<div class="rp-a" id="rp-a' + i + '" hidden><p>' + q[1] + '</p>' +
      '<div class="rp-rate" role="group" aria-label="¿Lo recordaste?"><span>¿Lo recordaste?</span>' +
      '<button type="button" data-v="2">Sí</button><button type="button" data-v="1">Más o menos</button><button type="button" data-v="0">No</button></div></div></li>';
  });
  html += '</ol><div class="rp-end" hidden aria-live="polite"><p class="rp-score"></p>' +
    '<div class="rp-reto"><p class="rp-reto-h">Ponlo en práctica hoy</p><p>' + data.reto + '</p></div>' +
    '<div class="actions"><button class="btn btn-primary rp-cal" type="button">' + (window.AMT ? 'Agregar a mis repasos' : 'Recuérdame repasar en 3 días') + '</button>' +
    '<button class="btn btn-secondary rp-otra" type="button">Intentar de nuevo</button></div>' +
    '<p class="rp-nota">' + (window.AMT ? 'Se guarda en Repaso activo y te ofrece agregar los próximos repasos a tu calendario. No necesitas cuenta ni correo.' : 'El recordatorio se agrega al calendario de tu teléfono o computadora. No necesitas cuenta ni correo.') + '</p></div>';
  box.innerHTML = html;
  box.setAttribute('aria-labelledby', 'rp-t');
  /* Dentro del visor de Claude no se pueden descargar archivos de calendario: se ofrece Google Calendar. */
  if(!window.AMT && window.claude && typeof window.claude.use === 'function'){
    var g = box.querySelector('.rp-cal'), d = new Date(Date.now() + 3 * 864e5); d.setSeconds(0, 0);
    if(d.getHours() < 7 || d.getHours() >= 21) d.setHours(19, 0);
    var q = function(n){ return ('0' + n).slice(-2); }, F = function(x){ return x.getFullYear() + q(x.getMonth() + 1) + q(x.getDate()) + 'T' + q(x.getHours()) + q(x.getMinutes()) + '00'; };
    var href = 'https://calendar.google.com/calendar/render?action=TEMPLATE&text=' + encodeURIComponent('Repaso: ' + (art.titulo || document.title)) +
      '&dates=' + F(d) + '/' + F(new Date(d.getTime() + 15 * 6e4)) + '&details=' + encodeURIComponent('Antes de abrir el artículo, intenta responder las preguntas de memoria.');
    var link = document.createElement('a'); link.className = 'btn btn-primary'; link.href = href; link.target = '_blank'; link.rel = 'noopener';
    link.textContent = 'Recuérdame en 3 días (Google Calendar)'; g.replaceWith(link);
    box.querySelector('.rp-nota').textContent = 'Aquí, dentro de Claude, se usa Google Calendar. En tu sitio publicado el botón agrega el recordatorio al calendario de tu teléfono.';
  }

  var end = box.querySelector('.rp-end');
  box.addEventListener('click', function(e){
    var b = e.target.closest('button'); if(!b) return;
    var li = b.closest('.rp-q');
    if(b.classList.contains('rp-ver')){
      li.querySelector('.rp-a').hidden = false; b.setAttribute('aria-expanded', 'true'); b.hidden = true;
      if(!box.dataset.started){ box.dataset.started = 1; track('repaso_inicio'); }
      return;
    }
    if(b.dataset.v != null && li){
      notas[li.dataset.i] = +b.dataset.v;
      li.setAttribute('data-r', b.dataset.v);
      li.querySelectorAll('.rp-rate button').forEach(function(x){ x.setAttribute('aria-pressed', x === b ? 'true' : 'false'); });
      if(Object.keys(notas).length === N) terminar();
      return;
    }
    if(b.classList.contains('rp-cal')){ if(window.AMT) aMisRepasos(); else calendario(); track('repaso_calendario'); return; }
    if(b.classList.contains('rp-otra')){ notas = {}; delete box.dataset.started;
      box.querySelectorAll('.rp-q').forEach(function(q){ q.removeAttribute('data-r'); q.querySelector('.rp-a').hidden = true;
        var v = q.querySelector('.rp-ver'); v.hidden = false; v.setAttribute('aria-expanded', 'false');
        q.querySelectorAll('[aria-pressed]').forEach(function(x){ x.removeAttribute('aria-pressed'); }); });
      end.hidden = true; box.querySelector('.rp-q .rp-ver').focus(); }
  });

  function terminar(){
    var bien = 0, medio = 0;
    for(var k in notas){ if(notas[k] === 2) bien++; else if(notas[k] === 1) medio++; }
    var msg = 'Recordaste ' + bien + ' de ' + N + (medio ? ', y ' + medio + ' más o menos' : '') + '. ';
    msg += bien === N ? 'Muy bien. Para que dure, vuelve a intentarlo en unos días, sin releer antes.'
         : 'Lo que no recordaste es justo lo que más vale repasar. No es un examen: el esfuerzo de intentarlo ya está ayudando a que se quede.';
    end.querySelector('.rp-score').textContent = msg;
    end.hidden = false;
    guardar({fecha: Date.now(), bien: bien, medio: medio});
    track('repaso_fin');
  }

  /* Con las herramientas cargadas: el artículo se guarda en "Repaso activo", con sus preguntas como apuntes */
  function aMisRepasos(){
    var A = window.AMT, lista = A.store.get('repasos', []), h = A.hoy0().getTime(), tema = 'Artículo ' + num + ': ' + (art.titulo || document.title);
    var r = lista.filter(function(x){ return x.tema === tema; })[0];
    if(!r){
      var plain = function(t){ var d = document.createElement('div'); d.innerHTML = t; return d.textContent; };
      r = {tema: tema, fechas: [0, 3, 7, 14, 30].map(function(n){ return h + n * A.DIA; }), hechos: [h], hora: 19,
           apuntes: data.preguntas.map(function(q, i){ return (i + 1) + '. ' + plain(q[0]) + '\n' + plain(q[1]); }).join('\n\n')};
      lista.unshift(r); A.store.set('repasos', lista);
    }
    var nota = box.querySelector('.rp-nota');
    nota.innerHTML = 'Guardado en <a href="herramienta-calendario-repaso.html">Repaso activo</a>, con estas preguntas como apuntes. Ahí verás cuándo te toca repasar.';
    A.ics(r.fechas.filter(function(f){ return f > h; }).map(function(f){ var d = new Date(f); d.setHours(19, 0, 0, 0);
      return {titulo: 'Repaso: ' + (art.titulo || document.title), inicio: d, minutos: 15, detalle: 'Antes de abrir el artículo, intenta responder las preguntas de memoria. ' + (window.AM_CONFIG ? AM_CONFIG.dominio : '') + '/' + (art.href || '') + '#repaso'}; }), 'repaso-articulo-' + num + '.ics');
  }

  function calendario(){
    var d = new Date(Date.now() + 3 * 864e5); d.setSeconds(0, 0);
    if(d.getHours() < 7 || d.getHours() >= 21){ d.setHours(19, 0); } /* nunca de madrugada ni muy noche */
    var p = function(n){ return ('0' + n).slice(-2); };
    var f = function(x){ return x.getFullYear() + p(x.getMonth() + 1) + p(x.getDate()) + 'T' + p(x.getHours()) + p(x.getMinutes()) + '00'; };
    var fin = new Date(d.getTime() + 15 * 6e4);
    var dom = (window.AM_CONFIG && AM_CONFIG.dominio) || location.origin;
    var url = dom + '/' + (art.href || location.pathname.split('/').pop()) + '#repaso';
    var tit = 'Repaso: ' + (art.titulo || document.title).replace(/[\\,;]/g, function(c){ return '\\' + c; });
    var ics = ['BEGIN:VCALENDAR','VERSION:2.0','PRODID:-//AriasMind//Repaso//ES','BEGIN:VEVENT',
      'UID:repaso-' + num + '-' + Date.now() + '@ariasmind.com',
      'DTSTAMP:' + new Date().toISOString().replace(/[-:]/g, '').slice(0, 15) + 'Z',
      'DTSTART:' + f(d), 'DTEND:' + f(fin),
      'SUMMARY:' + tit,
      'DESCRIPTION:Antes de abrir el artículo\\, intenta responder las preguntas de memoria. ' + url,
      'URL:' + url,
      'BEGIN:VALARM','TRIGGER:PT0M','ACTION:DISPLAY','DESCRIPTION:' + tit,'END:VALARM',
      'END:VEVENT','END:VCALENDAR'].join('\r\n');
    try{
      var a = document.createElement('a');
      a.href = URL.createObjectURL(new Blob([ics], {type: 'text/calendar'}));
      a.download = 'repaso-ariasmind-' + num + '.ics';
      document.body.appendChild(a); a.click(); a.remove();
    }catch(e){ location.href = 'data:text/calendar;charset=utf-8,' + encodeURIComponent(ics); }
  }
})();
